// =============================================
// SET LANGUAGE
// =============================================
function setLanguage(lang) {
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (translations[lang] && translations[lang][key] !== undefined) {
      el.innerHTML = translations[lang][key];
    }
  });

  // Update active state on toggle
  document.getElementById('langEN').classList.toggle('active', lang === 'en');
  document.getElementById('langPT').classList.toggle('active', lang === 'pt');
  document.getElementById('langFR').classList.toggle('active', lang === 'fr');

  // Update html lang attribute
  document.documentElement.setAttribute('lang', lang);

  // Save preference
  localStorage.setItem('lang', lang);
}

// =============================================
// LANGUAGE TOGGLE
// =============================================
const langToggle = document.getElementById('langToggle');
langToggle.addEventListener('click', () => {
  const current = localStorage.getItem('lang') || 'pt';
  const cycle = { en: 'pt', pt: 'fr', fr: 'en' };
  setLanguage(cycle[current] || 'pt');
});

// Detect initial language: saved preference > browser language > default PT
const savedLang = localStorage.getItem('lang');
const browserLang = navigator.language.startsWith('pt') ? 'pt' : navigator.language.startsWith('fr') ? 'fr' : 'en';
setLanguage(savedLang || browserLang);

// =============================================
// CUSTOM CURSOR
// =============================================
const cursor = document.getElementById('cursor');
const ring = document.getElementById('cursorRing');
let mx = 0, my = 0, rx = 0, ry = 0;

document.addEventListener('mousemove', e => {
  mx = e.clientX;
  my = e.clientY;
});

function animateCursor() {
  cursor.style.left = mx + 'px';
  cursor.style.top = my + 'px';
  rx += (mx - rx) * 0.12;
  ry += (my - ry) * 0.12;
  ring.style.left = rx + 'px';
  ring.style.top = ry + 'px';
  requestAnimationFrame(animateCursor);
}
animateCursor();

const addHoverEvents = () => {
  document.querySelectorAll('a, button, .project-card, .service-row, .skill-item, .lightbox-close, .lang-toggle').forEach(el => {
    el.addEventListener('mouseenter', () => document.body.classList.add('hovering'));
    el.addEventListener('mouseleave', () => document.body.classList.remove('hovering'));
  });
};
addHoverEvents();

// =============================================
// NAV SCROLL
// =============================================
window.addEventListener('scroll', () => {
  document.getElementById('nav').classList.toggle('scrolled', window.scrollY > 50);
});

// =============================================
// REVEAL ON SCROLL
// =============================================
const reveals = document.querySelectorAll('.reveal');
const obs = new IntersectionObserver((entries) => {
  entries.forEach(e => {
    if (e.isIntersecting) {
      e.target.classList.add('visible');
      obs.unobserve(e.target);
    }
  });
}, { threshold: 0.1 });

reveals.forEach(r => obs.observe(r));

// =============================================
// LIGHTBOX
// =============================================
const lightbox = document.getElementById('lightbox');
const lightboxContent = document.getElementById('lightboxContent');
const lightboxClose = document.getElementById('lightboxClose');

document.querySelectorAll('.project-card').forEach(card => {
  card.addEventListener('click', () => {
    const images = card.getAttribute('data-images');
    if (images) {
      lightboxContent.innerHTML = '';
      images.split(',').forEach(src => {
        const img = document.createElement('img');
        img.src = src;
        lightboxContent.appendChild(img);
      });
      lightbox.classList.add('active');
      document.body.classList.add('lightbox-open');
    }
  });
});

lightboxClose.addEventListener('click', () => {
  lightbox.classList.remove('active');
  document.body.classList.remove('lightbox-open');
});

lightbox.addEventListener('click', (e) => {
  if (e.target === lightbox) {
    lightbox.classList.remove('active');
    document.body.classList.remove('lightbox-open');
  }
});

// Close lightbox with Escape key
document.addEventListener('keydown', (e) => {
  if (e.key === 'Escape' && lightbox.classList.contains('active')) {
    lightbox.classList.remove('active');
    document.body.classList.remove('lightbox-open');
  }
});
